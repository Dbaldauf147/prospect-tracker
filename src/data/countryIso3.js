// The canonical country name for an ISO alpha-3 code, or null when the
// input isn't one. Anything that isn't exactly three letters is rejected
// up front so a real country name never reaches the map.
export function countryNameFromIso3(raw) {
  const code = String(raw || '').trim().toUpperCase();
  if (!/^[A-Z]{3}$/.test(code)) return null;
  return ISO3_TO_COUNTRY[code] || null;
}
